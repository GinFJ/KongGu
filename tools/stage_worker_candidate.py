"""Stage an audited candidate under Tauri's stable runtime registration name.

Previous generated workers are retained by content hash before atomic replacement.
The candidate directory remains the provenance source; development source is untouched.
"""
from __future__ import annotations
import argparse
import hashlib
import os
from pathlib import Path
import shutil
import uuid

ROOT = Path(__file__).resolve().parents[1]
NAME = 'konggu-worker-x86_64-pc-windows-msvc.exe'


def digest(path: Path) -> str:
    with path.open('rb') as handle:
        return hashlib.file_digest(handle, 'sha256').hexdigest()


def stage(candidate: Path, root: Path = ROOT) -> Path:
    root = root.resolve(strict=True)
    candidate = candidate.resolve(strict=True)
    if candidate.name != NAME:
        raise ValueError('Use the audited Windows x64 candidate worker.')
    target = root/'src-tauri/binaries'/NAME
    target.parent.mkdir(parents=True, exist_ok=True)
    if not target.resolve().is_relative_to(root):
        raise ValueError('The generated sidecar path must stay inside the project.')
    wanted = digest(candidate)
    if target.exists():
        old = digest(target)
        if old == wanted:
            return target
        backup = root/'build/sidecar-history'/old/NAME
        backup.parent.mkdir(parents=True, exist_ok=True)
        if not backup.exists():
            with target.open('rb') as source, backup.open('xb') as destination:
                shutil.copyfileobj(source, destination)
        if digest(backup) != old:
            raise ValueError('Previous generated worker backup failed integrity validation.')
    temporary = target.with_name('.stage-'+uuid.uuid4().hex+'.exe')
    try:
        shutil.copy2(candidate, temporary)
        if digest(temporary) != wanted:
            raise ValueError('Staged candidate bytes differ from the audited worker.')
        os.replace(temporary, target)
    finally:
        if temporary.exists():
            temporary.unlink()
    return target


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--candidate', type=Path, required=True)
    args=parser.parse_args()
    target=stage(args.candidate)
    print('Stable runtime registration staged; previous generated bytes retained by hash.')
